#[derive(Clone, Copy, PartialEq, Eq, Debug, serde::Serialize, serde::Deserialize)]
pub enum Lang {
    Ru,
    En,
}

impl Lang {
    pub fn from_system() -> Lang {
        match sys_locale::get_locale() {
            Some(l) if l.to_lowercase().starts_with("ru") => Lang::Ru,
            _ => Lang::En,
        }
    }
}


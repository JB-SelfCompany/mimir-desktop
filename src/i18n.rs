/// File size units, bytes to GiB (AM §12.C: localized, unlike Android's hard-coded B/KB/MB).
pub fn size_units(lang: Lang) -> [&'static str; 4] {
    match lang {
        Lang::Ru => ["Б", "КБ", "МБ", "ГБ"],
        Lang::En => ["B", "KB", "MB", "GB"],
    }
}

/// `tr` with its Android placeholders filled: `%1$s`/`%2$d` by position, bare `%s`/`%d` in order.
pub fn trf(lang: Lang, key: Key, args: &[&str]) -> String {
    let (mut out, mut rest, mut next) = (String::new(), tr(lang, key), 0);
    while let Some(i) = rest.find('%') {
        out.push_str(&rest[..i]);
        let tail = &rest[i + 1..];
        let digits = tail.bytes().take_while(u8::is_ascii_digit).count();
        let (arg, skip) = if digits > 0 && tail[digits..].starts_with('$') {
            (tail[..digits].parse::<usize>().unwrap_or(1).saturating_sub(1), digits + 2)
        } else {
            next += 1;
            (next - 1, 1)
        };
        out.push_str(args.get(arg).copied().unwrap_or_default());
        rest = tail.get(skip..).unwrap_or_default();
    }
    out.push_str(rest);
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn tr_has_both_languages() {
        assert_eq!(tr(Lang::Ru, Key::SavedMessages), "Избранное");
        assert_eq!(tr(Lang::En, Key::SavedMessages), "Saved Messages");
    }
    #[test]
    fn trf_fills_android_placeholders() {
        assert_eq!(trf(Lang::Ru, Key::MemberCount, &["2", "1"]), "2 участников, 1 в сети");
        assert_eq!(trf(Lang::Ru, Key::DownloadFailed, &["x"]), "Не удалось получить файл: x");
        assert_eq!(trf(Lang::En, Key::DownloadFailed, &["x"]), "Download failed: x");
        assert_eq!(trf(Lang::En, Key::SystemMsgRoleChanged, &["A", "B", "Admin"]), "A changed B role to Admin");
        assert_eq!(trf(Lang::Ru, Key::ChannelSubscribers, &["40"]), "40 подписчиков,  в сети", "missing argument is empty");
    }
}
